-- Run once in Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Safe to re-run: CREATE TABLE IF NOT EXISTS does not delete existing rows.
-- Demo schema. Anonymous web clients have no table access; the .NET SERVER
-- connects with Postgres credentials stored in local user-secrets, never JS.

CREATE TABLE IF NOT EXISTS public.study_tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) > 0),
    subject varchar(80) NOT NULL CHECK (length(btrim(subject)) > 0),
    deadline date NOT NULL,
    is_done boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.study_students (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL CHECK (length(btrim(name)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.study_practice_exams (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES public.study_students(id) ON DELETE CASCADE,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) > 0),
    taken_on date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.study_subject_scores (
    exam_id integer NOT NULL REFERENCES public.study_practice_exams(id) ON DELETE CASCADE,
    subject varchar(80) NOT NULL CHECK (length(btrim(subject)) > 0),
    score integer NOT NULL CHECK (score >= 0),
    max_score integer NOT NULL CHECK (max_score BETWEEN 1 AND 1000),
    PRIMARY KEY (exam_id, subject),
    CONSTRAINT study_subject_score_within_max CHECK (score <= max_score)
);

CREATE INDEX IF NOT EXISTS idx_study_tasks_deadline ON public.study_tasks(deadline);
CREATE INDEX IF NOT EXISTS idx_study_exams_student_date
    ON public.study_practice_exams(student_id, taken_on DESC);

-- Public API access is denied until users, auth and per-user RLS policies exist.
ALTER TABLE public.study_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_practice_exams ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_subject_scores ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.study_tasks, public.study_students,
    public.study_practice_exams, public.study_subject_scores FROM anon, authenticated;

-- No DROP, TRUNCATE, or demo student records here.
