-- Run once in Supabase Dashboard > SQL Editor.
-- These names match the current StudyFlow project. Auth owns each row; RLS isolates users.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '' check (char_length(display_name)<=100),
  created_at timestamptz not null default now()
);

create or replace function public.studyflow_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id,display_name)
  values(new.id,left(coalesce(new.raw_user_meta_data->>'display_name',''),100))
  on conflict(id) do nothing;
  return new;
end;
$$;
drop trigger if exists studyflow_user_created on auth.users;
create trigger studyflow_user_created after insert on auth.users
for each row execute function public.studyflow_new_user();

create table if not exists public.sf_tasks (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title varchar(200) not null check(length(btrim(title))>0),
  subject varchar(80) not null check(length(btrim(subject))>0),
  deadline date not null,
  is_done boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists sf_tasks_owner_deadline_idx on public.sf_tasks(owner_id,deadline);

create table if not exists public.sf_practice_exams (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title varchar(200) not null check(length(btrim(title))>0),
  taken_on date not null,
  created_at timestamptz not null default now(),
  unique(id,owner_id)
);
create table if not exists public.sf_subject_scores (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  exam_id bigint not null,
  subject varchar(80) not null check(length(btrim(subject))>0),
  score integer not null check(score>=0),
  max_score integer not null check(max_score between 1 and 1000),
  unique(exam_id,subject),
  foreign key(exam_id,owner_id) references public.sf_practice_exams(id,owner_id) on delete cascade,
  check(score<=max_score)
);

alter table public.profiles enable row level security;
alter table public.sf_tasks enable row level security;
alter table public.sf_practice_exams enable row level security;
alter table public.sf_subject_scores enable row level security;

drop policy if exists profile_owner_only on public.profiles;
create policy profile_owner_only on public.profiles for all to authenticated
using ((select auth.uid())=id) with check ((select auth.uid())=id);
drop policy if exists tasks_owner_only on public.sf_tasks;
create policy tasks_owner_only on public.sf_tasks for all to authenticated
using ((select auth.uid())=owner_id) with check ((select auth.uid())=owner_id);
drop policy if exists exams_owner_only on public.sf_practice_exams;
create policy exams_owner_only on public.sf_practice_exams for all to authenticated
using ((select auth.uid())=owner_id) with check ((select auth.uid())=owner_id);
drop policy if exists scores_owner_only on public.sf_subject_scores;
create policy scores_owner_only on public.sf_subject_scores for all to authenticated
using ((select auth.uid())=owner_id) with check ((select auth.uid())=owner_id);

grant usage on schema public to authenticated;
grant select,insert,update,delete on public.profiles,public.sf_tasks,public.sf_practice_exams,public.sf_subject_scores to authenticated;
grant usage,select on sequence public.sf_tasks_id_seq, public.sf_practice_exams_id_seq, public.sf_subject_scores_id_seq to authenticated;
